/*
 * harness-statelessness.js
 * Act 3 panel — "Even the Chat Box Is a Harness"
 *
 * Renders a real recorded pair of API runs: the same three user turns sent
 * twice, once carrying the conversation forward and once not. The reader
 * steps through the turns and watches the request payload grow (or not).
 *
 * Data: media/research/harness/statelessness.json, written verbatim by
 * figure_generation/harness/record_statelessness.py. Nothing here invents
 * model output. If the recording is absent the panel says so plainly rather
 * than showing placeholder content — see renderPending().
 */
(function () {
    "use strict";

    var root = document.getElementById("statelessness-panel");
    if (!root) return;

    var DATA_URL = root.getAttribute("data-src");
    var state = { data: null, run: "stateful", turn: 1 };

    /* ---------- helpers ---------- */

    function el(tag, cls, text) {
        var n = document.createElement(tag);
        if (cls) n.className = cls;
        if (text != null) n.textContent = text;
        return n;
    }

    function fmtPayload(turn, run, data) {
        // Reconstruct the request as it was actually sent, for display.
        var lines = [];
        lines.push("POST /v1/messages");
        lines.push("{");
        lines.push('  "model": ' + JSON.stringify(data.model) + ",");
        lines.push('  "system": ' + JSON.stringify(data.system) + ",");
        lines.push('  "messages": [');
        turn.request_messages.forEach(function (m, i) {
            var comma = i < turn.request_messages.length - 1 ? "," : "";
            lines.push('    { "role": ' + JSON.stringify(m.role) +
                       ', "content": ' + JSON.stringify(m.content) + " }" + comma);
        });
        lines.push("  ]");
        lines.push("}");
        return lines.join("\n");
    }

    /* ---------- states ---------- */

    function renderPending(msg) {
        root.innerHTML = "";
        var body = el("div", "hz-panel-body");
        var p = el("p", "hz-panel-fallback");
        p.innerHTML =
            "<b>Recording pending.</b> This panel shows a real pair of API runs, " +
            "not a simulation. The transcript has not been recorded yet, so there is " +
            "nothing to display. That is deliberate, rather than filling the space " +
            "with invented model output." +
            (msg ? " <span style='opacity:.7'>(" + msg + ")</span>" : "");
        body.appendChild(p);
        var how = el("p", "hz-panel-fallback");
        how.style.marginTop = "10px";
        how.innerHTML = "Generated by <code>figure_generation/harness/" +
                        "record_statelessness.py</code>.";
        body.appendChild(how);
        root.appendChild(body);
    }

    function render() {
        var data = state.data;
        var run = data.runs[state.run];
        var turn = run.turns[state.turn - 1];

        root.innerHTML = "";

        /* head: run toggle */
        var head = el("div", "hz-panel-head");
        var title = el("div", "hz-panel-title", "What actually gets sent");
        if (data._mock) {
            title.appendChild(document.createTextNode(" "));
            title.appendChild(el("span", "hz-illustrative", "illustrative"));
        }
        head.appendChild(title);

        var toggle = el("div", "hz-toggle");
        [["stateful", "History re-sent"], ["stateless", "Only latest turn"]].forEach(function (o) {
            var b = el("button", "hz-btn" + (state.run === o[0] ? " is-on" : ""), o[1]);
            b.type = "button";
            b.setAttribute("aria-pressed", String(state.run === o[0]));
            b.addEventListener("click", function () { state.run = o[0]; render(); });
            toggle.appendChild(b);
        });
        head.appendChild(toggle);
        root.appendChild(head);

        var body = el("div", "hz-panel-body");

        /* two columns: conversation | payload */
        var cols = el("div", "hz-cols");

        var left = el("div", "hz-col");
        left.appendChild(el("div", "hz-col-h", "The conversation"));
        run.turns.forEach(function (t, i) {
            var n = i + 1;
            var cur = n === state.turn;
            var past = n < state.turn;
            if (!cur && !past) return;

            var u = el("div", "hz-msg hz-msg-user" + (cur ? " is-current" : ""));
            u.appendChild(el("span", "hz-msg-role", "you"));
            u.appendChild(el("span", "hz-msg-text", t.user));
            left.appendChild(u);

            if (past || cur) {
                var a = el("div", "hz-msg hz-msg-model" + (cur ? " is-current" : ""));
                a.appendChild(el("span", "hz-msg-role", "model"));
                a.appendChild(el("span", "hz-msg-text", t.reply));
                left.appendChild(a);
            }
        });
        cols.appendChild(left);

        var right = el("div", "hz-col");
        right.appendChild(el("div", "hz-col-h", "The request sent on turn " + state.turn));
        var pre = el("pre", "hz-payload", fmtPayload(turn, run, data));
        right.appendChild(pre);

        var meter = el("div", "hz-meter");
        var big = el("span", "hz-meter-v", String(turn.input_tokens));
        meter.appendChild(big);
        meter.appendChild(el("span", "hz-meter-k", "input tokens billed on this turn"));
        right.appendChild(meter);

        /* the whole point: the trend across turns */
        var series = run.turns.map(function (t) { return t.input_tokens; });
        var trend = el("div", "hz-trend");
        series.forEach(function (v, i) {
            var chip = el("span", "hz-trend-v" + (i + 1 === state.turn ? " is-current" : ""), String(v));
            trend.appendChild(chip);
            if (i < series.length - 1) trend.appendChild(el("span", "hz-trend-sep", "→"));
        });
        var grew = series[series.length - 1] > series[0];
        trend.appendChild(el("span", "hz-trend-note",
            grew ? "  climbing: the history is re-sent, and re-paid for, every turn"
                 : "  flat: nothing is carried, so nothing is re-paid for"));
        right.appendChild(trend);
        cols.appendChild(right);

        body.appendChild(cols);

        /* turn stepper */
        var controls = el("div", "hz-panel-controls");
        controls.style.marginTop = "16px";
        var prev = el("button", "hz-btn", "← Previous turn");
        prev.type = "button";
        prev.disabled = state.turn === 1;
        prev.addEventListener("click", function () { state.turn--; render(); });

        var next = el("button", "hz-btn", "Next turn →");
        next.type = "button";
        next.disabled = state.turn === run.turns.length;
        next.addEventListener("click", function () { state.turn++; render(); });

        controls.appendChild(prev);
        controls.appendChild(next);
        controls.appendChild(el("span", "hz-panel-fallback",
            "turn " + state.turn + " of " + run.turns.length));
        body.appendChild(controls);

        var note = el("p", "hz-panel-fallback");
        note.style.marginTop = "12px";
        note.textContent = run.note;
        body.appendChild(note);

        var prov = el("p", "hz-panel-fallback");
        prov.style.marginTop = "6px";
        prov.style.opacity = "0.85";
        if (data._mock) {
            prov.innerHTML =
                "<b>Illustrative placeholder.</b> These replies and token counts are " +
                "written by hand to show the shape of the demonstration. They are not " +
                "measured output. A real recorded pair of runs replaces this before " +
                "publication.";
        } else {
            prov.textContent = "Recorded " + (data.recorded_at || "").slice(0, 10) +
                               " · " + data.model + " · verbatim, not hand-edited.";
        }
        body.appendChild(prov);

        root.appendChild(body);
    }

    /* ---------- load ---------- */
    /*
     * Prefer the real recording. Fall back to the illustrative mock so the act
     * reads end-to-end before the transcript is recorded — clearly labelled in
     * the UI, never passed off as measured. Dropping the real file in is the
     * whole swap: no code change, and the label disappears on its own.
     */

    var MOCK_URL = root.getAttribute("data-mock-src");

    function load(url) {
        return fetch(url, { cache: "no-cache" }).then(function (r) {
            if (!r.ok) throw new Error("HTTP " + r.status);
            return r.json();
        }).then(function (d) {
            if (!d || !d.runs || !d.runs.stateful || !d.runs.stateless) {
                throw new Error("unexpected shape");
            }
            return d;
        });
    }

    load(DATA_URL)
        .catch(function () { return MOCK_URL ? load(MOCK_URL) : Promise.reject(); })
        .then(function (d) { state.data = d; render(); })
        .catch(function (e) {
            renderPending(e && e.message ? e.message : String(e));
        });
})();
